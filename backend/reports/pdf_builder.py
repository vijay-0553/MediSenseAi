class NumberedCanvas(canvas.Canvas):
    """
    Two-pass canvas to dynamically compute and draw exact page numbers
    and persistent medical disclaimer footer on every page.
    """
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, page_count: int):
        self.saveState()
        # Top banner accent line in Primary Blue
        self.setStrokeColor(PRIMARY_BLUE)
        self.setLineWidth(3)
        self.line(36, A4[1] - 20, A4[0] - 36, A4[1] - 20)

        # Footer divider line
        self.setStrokeColor(BORDER_BLUE)
        self.setLineWidth(0.75)
        self.line(36, 46, A4[0] - 36, 46)

        # Footer disclaimer text (2-line centered format prevents page-edge clipping)
        self.setFont("Helvetica", 7.0)
        self.setFillColor(TEXT_GRAY)
        line1 = "This result is generated by an AI model and is intended for research/decision-support purposes only."
        line2 = "It is not a medical diagnosis and should not replace professional medical evaluation."
        self.drawCentredString(A4[0] / 2.0, 34, line1)
        self.drawCentredString(A4[0] / 2.0, 24, line2)

        # Page number and Left branding tag
        self.setFont("Helvetica", 7.0)
        self.drawString(36, 13, "MediSense AI - Diagnostic Support Platform")
        page_str = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(A4[0] - 36, 13, page_str)
        self.restoreState()


def create_bar_chart(probabilities: Dict[str, float], threshold: Optional[float] = None) -> Drawing:
    """
    Build a clean, high-precision horizontal bar chart flowable using ReportLab Drawing.
    - Top class or flagged classes in solid blue #1565C0
    - Other classes in light blue #90CAF9
    - Track background #F0F4F8
    """
    items = list(probabilities.items())
    num_bars = len(items)
    
    # Calculate dimensions
    is_dense = num_bars > 6
    bar_height = 9.5 if is_dense else 13.0
    gap = 3.5 if is_dense else 5.5
    label_font_size = 7.5 if is_dense else 8.5
    pct_font_size = 7.5 if is_dense else 8.5

    label_width = 82
    chart_width = 140
    total_width = label_width + chart_width + 48
    total_height = num_bars * (bar_height + gap) + 8

    d = Drawing(total_width, total_height)

    # Determine top value or thresholding
    max_val = max(probabilities.values()) if probabilities else 1.0

    for idx, (label, prob) in enumerate(items):
        y = (num_bars - 1 - idx) * (bar_height + gap) + 4

        clean_label = label.replace("_", " ")
        if len(clean_label) > 17:
            clean_label = clean_label[:15] + ".."
        d.add(String(label_width - 6, y + 1.5, clean_label, fontName="Helvetica", fontSize=label_font_size, textAnchor="end", fillColor=TEXT_DARK_NAVY))

        # Background track
        d.add(Rect(label_width, y, chart_width, bar_height, fillColor=BAR_TRACK_BG, strokeColor=BORDER_BLUE, strokeWidth=0.5))

        # Filled bar
        bar_fill_width = max(1.5, min(chart_width, prob * chart_width))
        is_highlighted = (prob >= threshold) if threshold is not None else (prob == max_val and prob > 0)
        bar_color = BAR_TOP_BLUE if is_highlighted else BAR_OTHER_BLUE
        
        d.add(Rect(label_width, y, bar_fill_width, bar_height, fillColor=bar_color, strokeColor=None))

        # Percentage string
        pct_text = f"{prob * 100:.1f}%"
        text_color = BAR_TOP_BLUE if is_highlighted else TEXT_GRAY
        font_name = "Helvetica-Bold" if is_highlighted else "Helvetica"
        d.add(String(label_width + chart_width + 6, y + 1.5, pct_text, fontName=font_name, fontSize=pct_font_size, fillColor=text_color))

    return d


def build_report_pdf(
    result: Dict[str, Any],
    patient: Optional[Dict[str, Any]] = None,
    image_path: Optional[str] = None,
    output_pdf_path: Optional[str] = None,
) -> str:
    """
    Compile full PDF report to output_pdf_path (or storage/reports/<report_id>/report.pdf).
    Follows strict Blue & White styling, dynamic A4 layout, and full section integrity.
    """
    report_id = result.get("report_id", "UNKNOWN")
    module = result.get("module", "xray")
    module_name = result.get("module_name", module.capitalize())

    from config import settings
    report_dir = settings.REPORTS_DIR / report_id

    if not output_pdf_path:
        report_dir.mkdir(parents=True, exist_ok=True)
        output_pdf_path = str(report_dir / "report.pdf")

    # Auto-resolve preview image if not explicitly provided
    if not image_path or not os.path.exists(image_path):
        preview_file = report_dir / "preview.png"
        if preview_file.exists():
            image_path = str(preview_file)

    doc = SimpleDocTemplate(
        output_pdf_path,
        pagesize=A4,
        leftMargin=36,
        rightMargin=36,
        topMargin=32,
        bottomMargin=54,
    )

    styles = getSampleStyleSheet()

    # Typography & Styles
    title_style = ParagraphStyle(
        "MainTitle",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=20,
        leading=24,
        textColor=DARK_NAVY_TITLE,
    )
    subtitle_style = ParagraphStyle(
        "SubTitle",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=10,
        leading=13,
        textColor=PRIMARY_BLUE,
    )
    section_title = ParagraphStyle(
        "SectionTitle",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=11,
        leading=15,
        textColor=PRIMARY_BLUE,
        spaceBefore=8,
        spaceAfter=4,
    )
    cell_bold = ParagraphStyle(
        "CellBold",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=9,
        leading=12,
        textColor=TEXT_DARK_NAVY,
    )
    cell_val = ParagraphStyle(
        "CellVal",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=9,
        leading=12,
        textColor=TEXT_DARK_NAVY,
    )
    notice_text = ParagraphStyle(
        "NoticeText",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=8.5,
        leading=12,
        textColor=TEXT_DARK_NAVY,
    )
    amber_notice_text = ParagraphStyle(
        "AmberNoticeText",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=8.5,
        leading=12,
        textColor=AMBER_WARNING_TEXT,
    )

    story = []

    # 1. Header Section
    header_data = [
        [
            Paragraph("<b>MediSense AI</b>", title_style),
            Paragraph(f"<b>Report ID:</b> {report_id}<br/><b>Date:</b> {result.get('timestamp', 'N/A')[:19].replace('T', ' ')} UTC", ParagraphStyle("HR", parent=styles["Normal"], fontName="Helvetica", fontSize=8.5, leading=12, alignment=2, textColor=TEXT_GRAY))
        ],
        [
            Paragraph("AI-Assisted X-ray Analysis Report", subtitle_style),
            Paragraph(f"<b>Status:</b> Completed", ParagraphStyle("HR2", parent=styles["Normal"], fontName="Helvetica-Bold", fontSize=8.5, leading=12, alignment=2, textColor=PRIMARY_BLUE))
        ]
    ]
    t_header = Table(header_data, colWidths=[320, 203])
    t_header.setStyle(TableStyle([
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 2),
        ("TOPPADDING", (0, 0), (-1, -1), 0),
        ("LEFTPADDING", (0, 0), (-1, -1), 0),
        ("RIGHTPADDING", (0, 0), (-1, -1), 0),
    ]))
    story.append(t_header)
    story.append(Spacer(1, 8))
    story.append(HRFlowable(width="100%", thickness=1.5, color=PRIMARY_BLUE, spaceAfter=10))

    # 2. Patient & Scan Details Cards
    p_name = (patient.get("name") if patient and patient.get("name") else "Not provided")
    p_age = (str(patient.get("age")) if patient and patient.get("age") is not None else "Not provided")
    p_sex = (patient.get("sex") if patient and patient.get("sex") else "Not provided")
    p_contact = (patient.get("contact") if patient and patient.get("contact") else "Not provided")

    info_card_data = [
        [
            Paragraph("<b>PATIENT INFORMATION</b>", cell_bold),
            Paragraph("<b>EXAMINATION & SCAN DETAILS</b>", cell_bold)
        ],
        [
            Paragraph(
                f"<b>Name:</b> {p_name}<br/>"
                f"<b>Age:</b> {p_age} &nbsp;&nbsp;&nbsp; <b>Sex:</b> {p_sex}<br/>"
                f"<b>Contact:</b> {p_contact}",
                cell_val
            ),
            Paragraph(
                f"<b>Module:</b> {module_name}<br/>"
                f"<b>Model:</b> {result.get('model_architecture', 'Deep Learning Model')}<br/>"
                f"<b>File:</b> {result.get('filename', 'xray_image')}<br/>"
                f"<b>Inference Time:</b> {result.get('inference_time_ms', 'N/A')} ms",
                cell_val
            )
        ]
    ]
    t_info = Table(info_card_data, colWidths=[255, 268])
    t_info.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (0, -1), LIGHT_BLUE_BG),
        ("BACKGROUND", (1, 0), (1, -1), colors.HexColor("#F8FAFC")),
        ("BOX", (0, 0), (0, -1), 1, BORDER_BLUE),
        ("BOX", (1, 0), (1, -1), 1, colors.HexColor("#E2E8F0")),
        ("TOPPADDING", (0, 0), (-1, -1), 6),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
        ("LEFTPADDING", (0, 0), (-1, -1), 8),
        ("RIGHTPADDING", (0, 0), (-1, -1), 8),
    ]))
    story.append(t_info)
    story.append(Spacer(1, 10))

    # 3. AI Prediction & Model Confidence Summary Block
    pred_val = result.get("prediction", "N/A")
    low_conf = result.get("low_confidence", False)

    if module == "spine":
        p_abn = result.get("probability_abnormal", 0.0)
        thresh = result.get("decision_threshold", 0.7574)
        summary_html = (
            f"<b>AI Prediction:</b> <font color='{PRIMARY_BLUE.hexval()}'><b>{pred_val}</b></font><br/>"
            f"<b>Abnormal Probability:</b> {p_abn * 100:.2f}% &nbsp;|&nbsp; <b>Decision Threshold:</b> {thresh * 100:.2f}%<br/>"
            f"<i>{result.get('interpretation_note', '')}</i>"
        )
    elif module == "chest":
        findings = result.get("flagged_findings", [])
        if findings:
            flagged_str = ", ".join([f"{f['pathology']} ({f['probability']*100:.1f}%)" for f in findings])
            summary_html = (
                f"<b>AI Prediction:</b> <font color='{PRIMARY_BLUE.hexval()}'><b>{len(findings)} Flagged Condition(s)</b></font><br/>"
                f"<b>Flagged Findings (Threshold 50.0%):</b> {flagged_str}<br/>"
                f"<i>{result.get('interpretation_note', '')}</i>"
            )
        else:
            summary_html = (
                f"<b>AI Prediction:</b> <font color='{PRIMARY_BLUE.hexval()}'><b>No Finding (Derived)</b></font><br/>"
                f"<b>Summary:</b> 0 of 14 monitored thoracic conditions exceed the 50.0% decision threshold.<br/>"
                f"<i>{result.get('interpretation_note', '')}</i>"
            )
    else:
        conf_val = result.get("confidence", 0.0)
        conf_str = f"{conf_val * 100:.2f}%"
        conf_warning = " <font color='#D97706'><b>[Low Confidence]</b></font>" if low_conf else ""
        summary_html = (
            f"<b>AI Prediction:</b> <font color='{PRIMARY_BLUE.hexval()}'><b>{pred_val}</b></font><br/>"
            f"<b>Model Confidence:</b> {conf_str}{conf_warning}<br/>"
            f"<i>{result.get('interpretation_note', '')}</i>"
        )

    t_summary = Table(
        [[Paragraph(summary_html, ParagraphStyle("SumP", parent=styles["Normal"], fontName="Helvetica", fontSize=9.5, leading=14, textColor=TEXT_DARK_NAVY))]],
        colWidths=[523]
    )
    t_summary.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), LIGHT_BLUE_BG),
        ("BOX", (0, 0), (-1, -1), 1.5, PRIMARY_BLUE),
        ("TOPPADDING", (0, 0), (-1, -1), 8),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
        ("LEFTPADDING", (0, 0), (-1, -1), 10),
        ("RIGHTPADDING", (0, 0), (-1, -1), 10),
    ]))
    story.append(t_summary)
    story.append(Spacer(1, 10))

    # 4. Radiograph Image & Chart
    img_flowable = None
    if image_path and os.path.exists(image_path):
        try:
            with PILImage.open(image_path) as pil_img:
                w, h = pil_img.size
                max_w = 195
                max_h = 215
                scale = min(max_w / w, max_h / h)
                img_flowable = Image(image_path, width=w * scale, height=h * scale)
        except Exception as e:
            img_flowable = Paragraph(f"<i>Could not render radiograph: {e}</i>", cell_val)
    else:
        img_flowable = Paragraph("<i>Radiograph image not available</i>", cell_val)

    # Probabilities Table and Chart
    probs_dict = result.get("probabilities") or result.get("all_probabilities") or {}
    
    # For chest, ensure all 14 labels sorted high to low
    if module == "chest":
        sorted_probs = dict(sorted(probs_dict.items(), key=lambda item: item[1], reverse=True))
    else:
        sorted_probs = probs_dict

    threshold_for_chart = result.get("decision_threshold", 0.50 if module == "chest" else None)
    chart = create_bar_chart(sorted_probs, threshold=threshold_for_chart)

    image_box = Table(
        [
            [Paragraph("<b>ACQUIRED RADIOGRAPH</b>", cell_bold)],
            [img_flowable]
        ],
        colWidths=[205]
    )
    image_box.setStyle(TableStyle([
        ("ALIGN", (0, 1), (0, 1), "CENTER"),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("BOX", (0, 0), (-1, -1), 1, BORDER_BLUE),
        ("BACKGROUND", (0, 0), (0, 0), LIGHT_BLUE_BG),
        ("TOPPADDING", (0, 0), (-1, -1), 4),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
        ("LEFTPADDING", (0, 0), (-1, -1), 4),
        ("RIGHTPADDING", (0, 0), (-1, -1), 4),
    ]))

    chart_box = Table(
        [
            [Paragraph("<b>MODEL PROBABILITY DISTRIBUTION</b>", cell_bold)],
            [chart]
        ],
        colWidths=[310]
    )
    chart_box.setStyle(TableStyle([
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("BOX", (0, 0), (-1, -1), 1, BORDER_BLUE),
        ("BACKGROUND", (0, 0), (0, 0), LIGHT_BLUE_BG),
        ("TOPPADDING", (0, 0), (-1, -1), 4),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
        ("LEFTPADDING", (0, 0), (-1, -1), 6),
        ("RIGHTPADDING", (0, 0), (-1, -1), 4),
    ]))

    story.append(Table([[image_box, chart_box]], colWidths=[209, 314], style=[
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("LEFTPADDING", (0, 0), (-1, -1), 0),
        ("RIGHTPADDING", (0, 0), (-1, -1), 0),
        ("TOPPADDING", (0, 0), (-1, -1), 0),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 0),
    ]))
    story.append(Spacer(1, 10))

    # 5. Probability Table (All classes with exact numerical percentages)
    table_rows = [
        [
            Paragraph("<b>Class / Pathology</b>", cell_bold),
            Paragraph("<b>Probability</b>", ParagraphStyle("THP", parent=cell_bold, alignment=2)),
            Paragraph("<b>Status / Evaluation</b>", cell_bold)
        ]
    ]

    for label, prob in sorted_probs.items():
        is_top = (prob == max(sorted_probs.values())) and prob > 0
        is_flagged = (prob >= threshold_for_chart) if threshold_for_chart else is_top
        
        status_label = "Flagged &bull; Above Threshold" if is_flagged else ("Top Class" if is_top else "Normal Range")
        if module == "chest" and not is_flagged:
            status_label = "Below 50% Threshold"

        clean_label = label.replace("_", " ")
        prob_text = f"{prob * 100:.2f}%"
        
        row_font = "Helvetica-Bold" if (is_top or is_flagged) else "Helvetica"
        row_color = PRIMARY_BLUE if (is_top or is_flagged) else TEXT_DARK_NAVY

        table_rows.append([
            Paragraph(f"<font color='{row_color.hexval()}'><b>{clean_label}</b></font>" if (is_top or is_flagged) else clean_label, cell_val),
            Paragraph(f"<font color='{row_color.hexval()}'><b>{prob_text}</b></font>" if (is_top or is_flagged) else prob_text, ParagraphStyle("TP", parent=cell_val, fontName=row_font, alignment=2)),
            Paragraph(f"<font color='{row_color.hexval()}'>{status_label}</font>", cell_val),
        ])

    prob_table = Table(table_rows, colWidths=[200, 110, 213])
    t_style = [
        ("BACKGROUND", (0, 0), (-1, 0), PRIMARY_BLUE),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("BOX", (0, 0), (-1, -1), 1, BORDER_BLUE),
        ("INNERGRID", (0, 0), (-1, -1), 0.5, BORDER_BLUE),
        ("TOPPADDING", (0, 0), (-1, -1), 3),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
        ("LEFTPADDING", (0, 0), (-1, -1), 6),
        ("RIGHTPADDING", (0, 0), (-1, -1), 6),
    ]
    # Alternating row backgrounds
    for r_idx in range(1, len(table_rows)):
        if r_idx % 2 == 1:
            t_style.append(("BACKGROUND", (0, r_idx), (-1, r_idx), colors.white))
        else:
            t_style.append(("BACKGROUND", (0, r_idx), (-1, r_idx), LIGHT_BLUE_BG))

    prob_table.setStyle(TableStyle(t_style))
    story.append(KeepTogether([
        Paragraph("<b>Detailed Class Probabilities</b>", section_title),
        prob_table
    ]))
    story.append(Spacer(1, 8))

    # 6. Knee Reference Description (Knee only)
    if module == "knee" and result.get("reference_description"):
        ref_text = result.get("reference_description", "")
        if "standard KL grade description (reference, not a model output):" in ref_text:
            ref_content = f"<b>Clinical Reference:</b> {ref_text}"
        else:
            ref_content = f"<b>Clinical Reference:</b> standard KL grade description (reference, not a model output): {ref_text}"
        ref_p = Paragraph(ref_content, notice_text)
        ref_table = Table([[ref_p]], colWidths=[523])
        ref_table.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, -1), LIGHT_BLUE_BG),
            ("BOX", (0, 0), (-1, -1), 1, BORDER_BLUE),
            ("TOPPADDING", (0, 0), (-1, -1), 5),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
            ("LEFTPADDING", (0, 0), (-1, -1), 8),
            ("RIGHTPADDING", (0, 0), (-1, -1), 8),
        ]))
        story.append(KeepTogether([ref_table]))
        story.append(Spacer(1, 8))

    # 7. Notices & Caution Block (Amber only for caution, light blue for general)
    notices = result.get("notices", [])
    if notices:
        # Check if caution notice present
        has_caution = any(
            "training setup" in n.lower() or "below 50%" in n.lower() or "low confidence" in n.lower() or "screening" in n.lower()
            for n in notices
        )

        bg_color = AMBER_WARNING_BG if has_caution else LIGHT_BLUE_BG
        box_border = AMBER_WARNING_BORDER if has_caution else BORDER_BLUE
        text_style = amber_notice_text if has_caution else notice_text

        notice_items = "<br/>".join([f"&bull; {n}" for n in notices])
        notice_html = f"<b>IMPORTANT CLINICAL NOTICES &amp; MODEL LIMITATIONS:</b><br/>{notice_items}"
        notice_table = Table(
            [[Paragraph(notice_html, text_style)]],
            colWidths=[523]
        )
        notice_table.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, -1), bg_color),
            ("BOX", (0, 0), (-1, -1), 1, box_border),
            ("TOPPADDING", (0, 0), (-1, -1), 6),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
            ("LEFTPADDING", (0, 0), (-1, -1), 8),
            ("RIGHTPADDING", (0, 0), (-1, -1), 8),
        ]))
        story.append(KeepTogether([notice_table]))
        story.append(Spacer(1, 8))

    # Build document
    doc.build(story, canvasmaker=NumberedCanvas)
    return output_pdf_path
